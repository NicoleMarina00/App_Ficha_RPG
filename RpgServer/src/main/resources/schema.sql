CREATE TABLE IF NOT EXISTS PERSONAGEM (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    FORCA INT,
    INTELIGENCIA INT,
    DESTREZA INT,
    SABEDORIA INT,
    CARISMA INT,
    RACA_JSON VARCHAR(4000),
    CLASSE_JSON VARCHAR(4000),
    ARMA_JSON VARCHAR(4000),
    ARMADURA_JSON VARCHAR(4000),
    ESCUDO_JSON VARCHAR(4000),
    DIVINDADE_JSON VARCHAR(4000),
    PERICIA_JSON VARCHAR(4000),
    FEITICO_JSON VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS RACA (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255),
    HABILIDADE VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS CLASSE (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS ARMA (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255),
    VALOR_ATAQUE VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS ARMADURA (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255),
    VALOR_DEFESA VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS ESCUDO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255),
    VALOR_DEFESA VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS DIVINDADE (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS PERICIA (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS FEITICO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255),
    DESCRICAO VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS INVENTARIO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PERSONAGEM_ID INT NOT NULL,
    TIPO_ITEM VARCHAR(20) NOT NULL,
    ITEM_ID INT NOT NULL,
    QUANTIDADE INT NOT NULL CHECK (QUANTIDADE > 0),
    CONSTRAINT FK_INVENTARIO_PERSONAGEM FOREIGN KEY (PERSONAGEM_ID)
        REFERENCES PERSONAGEM(ID) ON DELETE CASCADE,
    CONSTRAINT CK_INVENTARIO_TIPO_ITEM CHECK (TIPO_ITEM IN ('ARMA', 'ARMADURA', 'ESCUDO'))
);
